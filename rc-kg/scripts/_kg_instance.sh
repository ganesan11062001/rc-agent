# shellcheck shell=bash
# Sourced by build_graph.sh and serve_kg.sh: one private Neo4j per caller.
#
# start_neo4j.sh is the single-developer path -- it writes its config into the
# shared vendor/ tree and its password into the repo's .env. That is wrong for
# anything launched from a Slurm job, where two jobs (or two users) can run at
# once from the same checkout. Here every instance gets its own directory on
# node-local disk holding config, store and logs; NEO4J_CONF points Neo4j at
# it, and nothing shared is written. The password is only ever in the
# environment of the processes that need it.
#
# Defines:  kg_instance_init DIR    kg_instance_load DUMP_DIR
#           kg_instance_start       kg_instance_stop
#           kg_new_dir LABEL        kg_sweep_stale        kg_list
# Exports after init:  NEO4J_CONF NEO4J_URI NEO4J_USER NEO4J_PASSWORD NEO4J_DATABASE

RC_KG_ROOT="${RC_KG_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
RC_KG_PY="$RC_KG_ROOT/.venv/bin/python"
NEO4J_HOME="$(echo "$RC_KG_ROOT"/vendor/neo4j-community-*)"
export NEO4J_HOME

kg_log() { echo "[rc-kg $(date +%H:%M:%S)] $*"; }

kg_free_port() {
  "$RC_KG_PY" -c 'import socket; s=socket.socket(); s.bind(("127.0.0.1",0)); print(s.getsockname()[1]); s.close()'
}

kg_instance_init() {
  KG_DIR="$1"
  [ -d "$NEO4J_HOME" ] || kg_die "Neo4j not found under $RC_KG_ROOT/vendor (run scripts/install_neo4j.sh)"
  [ -x "$RC_KG_PY" ] || kg_die "no venv at $RC_KG_ROOT/.venv"
  command -v java >/dev/null || kg_die "no java on PATH; Neo4j 5.26 needs JDK 17 or 21"

  # Node-local: Neo4j does not support its store on NFS (/projects, /scratch).
  mkdir -p "$KG_DIR"/{conf,data,logs,run} || kg_die "cannot create $KG_DIR"
  chmod 700 "$KG_DIR"

  local bolt; bolt="$(kg_free_port)"
  cat > "$KG_DIR/conf/neo4j.conf" <<EOF
# Generated by scripts/_kg_instance.sh for one job; deleted with it.
server.directories.data=$KG_DIR/data
server.directories.logs=$KG_DIR/logs
server.directories.run=$KG_DIR/run
server.directories.dumps.root=$KG_DIR/data/dumps
server.directories.import=$KG_DIR/import
# Loopback only, Bolt only. The HTTP browser is not needed by anything here.
server.default_listen_address=127.0.0.1
server.bolt.listen_address=127.0.0.1:$bolt
server.http.enabled=false
server.https.enabled=false
dbms.security.auth_enabled=true
# Sized for a few hundred sections.
server.memory.heap.initial_size=512m
server.memory.heap.max_size=1g
server.memory.pagecache.size=256m
EOF
  export NEO4J_CONF="$KG_DIR/conf"

  # The password lives only in this mode-700 directory and the environment of
  # this job's processes -- never on /projects.
  NEO4J_PASSWORD="$("$RC_KG_PY" -c 'import secrets; print(secrets.token_urlsafe(18))')"
  "$NEO4J_HOME/bin/neo4j-admin" dbms set-initial-password "$NEO4J_PASSWORD" >/dev/null \
    || kg_die "could not set the Neo4j password"
  export NEO4J_URI="bolt://127.0.0.1:$bolt" NEO4J_USER=neo4j NEO4J_PASSWORD NEO4J_DATABASE=neo4j
  KG_BOLT="$bolt"
}

kg_instance_load() {
  # Before start: neo4j-admin refuses to load into a running database.
  local from="$1"
  [ -f "$from/neo4j.dump" ] || kg_die "no neo4j.dump in $from"
  "$NEO4J_HOME/bin/neo4j-admin" database load neo4j --from-path="$from" \
    --overwrite-destination=true >"$KG_DIR/logs/load.log" 2>&1 \
    || { cat "$KG_DIR/logs/load.log" >&2; kg_die "loading $from/neo4j.dump failed"; }
}

kg_instance_start() {
  "$NEO4J_HOME/bin/neo4j" start >"$KG_DIR/logs/start.log" 2>&1 \
    || { tail -20 "$KG_DIR/logs/neo4j.log" "$KG_DIR/logs/start.log" 2>/dev/null >&2
         kg_die "neo4j start failed"; }
  # "started" is not "accepting Bolt"; poll the port the client needs.
  local _
  for _ in $(seq 1 90); do
    "$RC_KG_PY" - "$KG_BOLT" <<'PY' && return 0
import socket, sys
s = socket.socket(); s.settimeout(1)
sys.exit(0 if s.connect_ex(("127.0.0.1", int(sys.argv[1]))) == 0 else 1)
PY
    sleep 1
  done
  tail -20 "$KG_DIR/logs/neo4j.log" >&2
  kg_die "Neo4j never opened bolt on 127.0.0.1:$KG_BOLT"
}

kg_instance_stop() {
  [ -n "${NEO4J_CONF:-}" ] || return 0
  "$NEO4J_HOME/bin/neo4j" stop >/dev/null 2>&1 || true
}

# What the Python side needs to run offline and stay polite on a shared node.
kg_python_env() {
  # The embedding model lives on /projects next to the code, so every node
  # finds it, and is never fetched at serve time (compute nodes reach the Hub
  # only through a flaky proxy; see ticketmate/cluster/env.sh).
  export HF_HOME="$RC_KG_ROOT/vendor/hf"
  export HF_HUB_OFFLINE="${HF_HUB_OFFLINE:-1}" TRANSFORMERS_OFFLINE="${HF_HUB_OFFLINE:-1}"
  # Offline is intended; without this every start logs "could not reach the Hub".
  export HF_HUB_DISABLE_TELEMETRY=1 HF_HUB_VERBOSITY=error TOKENIZERS_PARALLELISM=false
  # Query embedding is one short CPU pass; do not let torch take every core
  # from the vLLM process sharing this allocation.
  export OMP_NUM_THREADS="${RC_KG_THREADS:-2}" MKL_NUM_THREADS="${RC_KG_THREADS:-2}"
  export PYTHONPATH="$RC_KG_ROOT${PYTHONPATH:+:$PYTHONPATH}"
}

# ── ownership, sweeping and listing ──────────────────────────────────────────
# Every instance dir is named rc_kg_<user>_<label>_XXXX under one parent and
# records who owns it: "<pid> <process start time>" of the creating script.
# The start time guards against PID reuse. A dir whose owner is gone is stale:
# whatever still runs from it (an orphaned Neo4j or API after a kill -9) is
# stopped and the dir removed. Only the caller's own dirs are ever touched.

KG_PARENT="${RC_KG_TMP:-${TMPDIR:-/tmp}}"

_kg_starttime() { awk '{print $22}' "/proc/$1/stat" 2>/dev/null; }

kg_new_dir() {
  local d
  d="$(mktemp -d "$KG_PARENT/rc_kg_${USER}_${1}_XXXX")" \
    || kg_die "cannot create an instance dir under $KG_PARENT"
  echo "$$ $(_kg_starttime $$)" > "$d/owner"
  echo "$d"
}

_kg_owner_alive() {
  local pid start
  read -r pid start < "$1/owner" 2>/dev/null || return 1
  [ -n "$pid" ] && [ "$(_kg_starttime "$pid")" = "$start" ]
}

# PIDs of this user's processes started from, or running inside, a dir.
_kg_procs_in() {
  local d="$1" p
  {
    for p in $(pgrep -u "$(id -u)" -f -- "$d" 2>/dev/null); do
      [ "$p" != "$$" ] && echo "$p"
    done
    for p in /proc/[0-9]*; do
      p="${p#/proc/}"
      [ "$p" = "$$" ] && continue
      [ "$(readlink "/proc/$p/cwd" 2>/dev/null)" = "$d" ] && echo "$p"
    done
  } | sort -un
}

kg_sweep_stale() {
  local d pids n=0
  for d in "$KG_PARENT"/rc_kg_"${USER}"_*; do
    [ -d "$d" ] && [ -O "$d" ] || continue
    _kg_owner_alive "$d" && continue
    pids="$(_kg_procs_in "$d" | sort -u | tr '\n' ' ')"
    if [ -n "${pids// /}" ]; then
      # shellcheck disable=SC2086
      kill $pids 2>/dev/null
      for _ in $(seq 1 15); do
        # shellcheck disable=SC2086
        kill -0 $pids 2>/dev/null || break
        sleep 1
      done
      # shellcheck disable=SC2086
      kill -9 $pids 2>/dev/null
    fi
    rm -rf "$d" && n=$((n + 1))
    kg_log "removed stale instance $(basename "$d")${pids:+ (stopped pids $pids)}"
  done
  return 0
}

kg_list() {
  local d state any=0
  for d in "$KG_PARENT"/rc_kg_"${USER}"_*; do
    [ -d "$d" ] || continue
    any=1
    if _kg_owner_alive "$d"; then state="live (owner pid $(cut -d' ' -f1 "$d/owner"))"
    else state="STALE"; fi
    printf '%-44s %-26s %5s MB  procs: %s\n' "$(basename "$d")" "$state" \
      "$(du -sm "$d" 2>/dev/null | cut -f1)" "$(_kg_procs_in "$d" | tr '\n' ' ')"
  done
  [ "$any" = 1 ] || echo "no rc-kg instances for $USER under $KG_PARENT on $(hostname -s)"
}

# Run in the background by a long-lived script: if the script disappears
# without running its own cleanup (kill -9, OOM kill), take down what it
# started. Usage: kg_watchdog <dir> & ; kill it in the script's own cleanup.
kg_watchdog() {
  local d="$1" owner="$$" start
  cd / || return        # do not count as a process inside the dir
  start="$(_kg_starttime "$owner")"
  # $$ in a subshell is still the parent script's PID, which is the point.
  while [ "$(_kg_starttime "$owner")" = "$start" ]; do sleep 3; done
  local pids; pids="$(_kg_procs_in "$d" | grep -v "^${BASHPID}$" | tr '\n' ' ')"
  # shellcheck disable=SC2086
  [ -n "${pids// /}" ] && kill $pids 2>/dev/null
  sleep 5
  # shellcheck disable=SC2086
  [ -n "${pids// /}" ] && kill -9 $pids 2>/dev/null
  rm -rf "$d"
}

# ── fast runtime: site-packages unpacked to node-local disk ──────────────────
# See build_runtime.sh for why. kg_runtime sets KG_PYTHON (an array: the
# command to run Python with) and prepends the right paths to PYTHONPATH.
# Without a current archive it falls back to the venv on /projects, which is
# correct, only slower.

KG_SITE="$(echo "$RC_KG_ROOT"/.venv/lib/python3*/site-packages)"
KG_RUNTIME_TAR="$RC_KG_ROOT/vendor/runtime/site-packages.tar"

# Fingerprint of what is installed: dist-info names carry the versions.
kg_runtime_stamp() {
  ls -1 "$KG_SITE" 2>/dev/null | grep -E '\.dist-info$' | sha256sum | cut -c1-16
}

kg_runtime() {
  KG_PYTHON=("$RC_KG_PY")
  local stamp; stamp="$(cat "${KG_RUNTIME_TAR%.tar}.stamp" 2>/dev/null)"
  if [ ! -f "$KG_RUNTIME_TAR" ] || [ -z "$stamp" ]; then
    kg_log "no runtime archive; importing from /projects (slow: run scripts/build_runtime.sh)"
    return 0
  fi
  if [ "$stamp" != "$(kg_runtime_stamp)" ]; then
    kg_log "runtime archive is out of date with the venv; importing from /projects (run scripts/build_runtime.sh)"
    return 0
  fi
  # One unpacked copy per user per node per package set, shared by that
  # user's instances on the node, so only the first one pays for it.
  local rt="$KG_PARENT/rc_kgrt_${USER}_${stamp}"
  if [ ! -f "$rt/.complete" ]; then
    local t0 tmp; t0=$(date +%s); tmp="$rt.tmp.$$"
    rm -rf "$tmp"; mkdir -p "$tmp" && chmod 700 "$tmp"
    if tar -C "$tmp" -xf "$KG_RUNTIME_TAR" && touch "$tmp/.complete"; then
      # Another instance may have finished first; theirs is as good as ours.
      mv -T "$tmp" "$rt" 2>/dev/null || rm -rf "$tmp"
      kg_log "unpacked runtime to $rt in $(( $(date +%s) - t0 ))s"
    else
      rm -rf "$tmp"
      kg_log "could not unpack runtime (disk full?); importing from /projects"
      return 0
    fi
  fi
  # The venv's base interpreter with the local packages instead of the venv's.
  # -s: no user site-packages from $HOME.
  KG_PYTHON=("$(readlink -f "$RC_KG_PY")" -s)
  # After the repo (kg_python_env put it first), so no package shadows our modules.
  export PYTHONPATH="${PYTHONPATH:+$PYTHONPATH:}$rt"
  # Unpacked copies for package sets no longer current are removed after a
  # day, by which time no instance started from them is still running.
  find "$KG_PARENT" -maxdepth 1 -name "rc_kgrt_${USER}_*" ! -name "rc_kgrt_${USER}_${stamp}" \
       -user "$USER" -mtime +1 -exec rm -rf {} + 2>/dev/null
  return 0
}

# ── graph variants ───────────────────────────────────────────────────────────
# Each variant is built, eval-gated and published separately:
#   full     RC website + rc-docs     data/graph/          (the default)
#   website  RC website only          data/graph-website/
# RC_KG_SNAPSHOT, if set, overrides the directory for any variant.
KG_VARIANTS="full website"

kg_snapshot_dir() {
  case "${1:-full}" in
    full)    echo "$RC_KG_ROOT/data/graph" ;;
    website) echo "$RC_KG_ROOT/data/graph-website" ;;
    *)       kg_die "unknown graph variant '$1' (expected: $KG_VARIANTS)" ;;
  esac
}

# Environment that makes the Python side build a given variant.
kg_variant_env() {
  case "${1:-full}" in
    full)    export DOCS_ENABLED=true ;;
    website) export DOCS_ENABLED=false ;;
    *)       kg_die "unknown graph variant '$1' (expected: $KG_VARIANTS)" ;;
  esac
}

# Sites a variant's eval may be judged on (questions with no expected URL on
# these sites are skipped: a website-only graph cannot answer a docs question).
kg_variant_sites() {
  case "${1:-full}" in
    full)    echo "rc.northeastern.edu,rc-docs.northeastern.edu" ;;
    website) echo "rc.northeastern.edu" ;;
  esac
}

# ── startup progress ─────────────────────────────────────────────────────────
# If RC_KG_PROGRESS_DIR is set (TicketMate sets it per session), each startup
# step writes <dir>/<step>.json: {"step","status","detail","at"} with status
# pending|running|done|failed. One writer per step file, written atomically,
# so a reader (TicketMate's /api/health) never sees a torn file. The API
# process writes its own steps the same way (api/app.py).
KG_CURRENT_STEP=""

kg_progress() {   # kg_progress <step> <status> [detail]
  [ -n "${RC_KG_PROGRESS_DIR:-}" ] || return 0
  mkdir -p "$RC_KG_PROGRESS_DIR" 2>/dev/null || return 0
  local detail="${3:-}"
  detail="${detail//\\/ }"; detail="${detail//\"/\'}"; detail="${detail//$'\n'/ }"
  local f="$RC_KG_PROGRESS_DIR/$1.json"
  printf '{"step":"%s","status":"%s","detail":"%s","at":"%s"}\n' \
    "$1" "$2" "${detail:0:300}" "$(date -Iseconds)" > "$f.tmp.$$" && mv -f "$f.tmp.$$" "$f"
  [ "$2" = running ] && KG_CURRENT_STEP="$1"
  return 0
}

# A fatal error marks whichever step was running as failed, with the reason.
kg_die() {
  echo "rc-kg ERROR: $*" >&2
  [ -n "$KG_CURRENT_STEP" ] && kg_progress "$KG_CURRENT_STEP" failed "$*"
  exit 1
}
