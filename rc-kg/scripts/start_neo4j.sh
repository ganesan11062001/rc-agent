#!/usr/bin/env bash
# Start the project's own Neo4j, as an ordinary user, with no container runtime.
#
#   ./scripts/start_neo4j.sh          start (picks free ports, writes .env)
#   ./scripts/start_neo4j.sh --status is it up?
#
# WHY NOT DOCKER
#   Explorer's compute nodes have no docker, podman, apptainer or singularity.
#   Neo4j 5.26 needs only a JVM, and /usr/bin/java is OpenJDK 17, so the tarball
#   runs unprivileged.
#
# WHY THE DATA DIRECTORY IS ON /tmp
#   Neo4j does not support running its store on NFS, and both /projects and
#   /scratch are NFS here. /tmp is node-local XFS (640 GB free). The cost is
#   that the store does not survive the node: that is acceptable because the
#   whole graph rebuilds from the WordPress API in a couple of minutes.
#   Use scripts/dump_neo4j.sh to keep a copy on /projects.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
NEO4J_HOME="$(echo "$ROOT"/vendor/neo4j-community-*)"
DATA_DIR="${RC_KG_DATA_DIR:-/tmp/rc_kg_neo4j}"
CONF="$NEO4J_HOME/conf/neo4j.conf"

die() { echo "ERROR: $*" >&2; exit 1; }

[ -d "$NEO4J_HOME" ] || die "Neo4j not found under $ROOT/vendor. Run scripts/install_neo4j.sh"
command -v java >/dev/null || die "no java on PATH; Neo4j 5.26 needs JDK 17 or 21"

# Neo4j owns $DATA_DIR/run/neo4j.pid. Writing our own pid there (which an
# earlier version of this script did) corrupts its tracking and makes `stop`
# and `status` disagree with reality -- so always ask the tool itself.
running() { "$NEO4J_HOME/bin/neo4j" status >/dev/null 2>&1; }

if [ "${1:-}" = "--status" ]; then
  if running; then
    "$NEO4J_HOME/bin/neo4j" status
    grep -E '^server\.(bolt|http)\.listen_address' "$CONF" | sed 's/^/  /'
    exit 0
  fi
  echo "not running"; exit 1
fi

if running; then
  echo "Already running. Ports:"
  "$NEO4J_HOME/bin/neo4j" status | sed 's/^/  /'
  grep -E '^server\.(bolt|http)\.listen_address' "$CONF" | sed 's/^/  /'
  exit 0
fi

mkdir -p "$DATA_DIR"/{data,logs,run} || die "cannot create $DATA_DIR"

# Ask the kernel for two free ports rather than hoping 7687/7474 are unused --
# on a shared node they often are not.
read -r BOLT HTTP <<<"$(python3 - <<'PY'
import socket
ports=[]
for _ in range(2):
    s=socket.socket(); s.bind(("127.0.0.1",0)); ports.append(s.getsockname()[1]); s.close()
print(*ports)
PY
)"
[ -n "${BOLT:-}" ] || die "could not allocate ports"

cat > "$CONF" <<EOF
# Generated by scripts/start_neo4j.sh -- edits here are overwritten on restart.
server.directories.data=$DATA_DIR/data
server.directories.logs=$DATA_DIR/logs
server.directories.run=$DATA_DIR/run

# Loopback only. This is an unauthenticated-by-default service on a node shared
# with other people's jobs; it must never bind 0.0.0.0.
server.default_listen_address=127.0.0.1
server.bolt.listen_address=127.0.0.1:$BOLT
server.http.listen_address=127.0.0.1:$HTTP
server.https.enabled=false
dbms.security.auth_enabled=true

# Sized for ~380 sections. The defaults would reserve several GB.
server.memory.heap.initial_size=1g
server.memory.heap.max_size=2g
server.memory.pagecache.size=512m
EOF

# A fresh store needs an initial password; an existing one keeps the old.
if [ ! -d "$DATA_DIR/data/databases/neo4j" ]; then
  PW="$(python3 -c 'import secrets;print(secrets.token_urlsafe(18))')"
  "$NEO4J_HOME/bin/neo4j-admin" dbms set-initial-password "$PW" >/dev/null \
    || die "could not set the initial password"
  echo "$PW" > "$DATA_DIR/password"; chmod 600 "$DATA_DIR/password"
  echo "new store created, password generated"
else
  PW="$(cat "$DATA_DIR/password")"
  echo "reusing the existing store at $DATA_DIR/data"
fi

# `neo4j start` daemonises and manages its own pidfile; `console` would need a
# nohup wrapper and leave us guessing about readiness.
"$NEO4J_HOME/bin/neo4j" start >/dev/null 2>&1 \
  || { tail -20 "$DATA_DIR/logs/neo4j.log" 2>/dev/null; die "neo4j start failed"; }

# "started" is not "accepting Bolt". Poll the port, which is what the client
# actually needs, rather than trusting a log line.
for _ in $(seq 1 60); do
  python3 - "$BOLT" <<'PY' && break
import socket, sys
s = socket.socket(); s.settimeout(1)
sys.exit(0 if s.connect_ex(("127.0.0.1", int(sys.argv[1]))) == 0 else 1)
PY
  sleep 2
done

python3 - "$BOLT" <<'PY' || { tail -20 "$DATA_DIR/logs/neo4j.log" 2>/dev/null; die "Neo4j never opened bolt on 127.0.0.1:$BOLT"; }
import socket, sys
s = socket.socket(); s.settimeout(1)
sys.exit(0 if s.connect_ex(("127.0.0.1", int(sys.argv[1]))) == 0 else 1)
PY

# Write connection details where the Python code looks for them. Only the
# NEO4J_* lines are rewritten, so hand-edited settings survive.
ENV="$ROOT/.env"
touch "$ENV"; chmod 600 "$ENV"
grep -vE '^NEO4J_(URI|USER|PASSWORD|DATABASE)=' "$ENV" > "$ENV.tmp" 2>/dev/null || true
{
  echo "NEO4J_URI=bolt://127.0.0.1:$BOLT"
  echo "NEO4J_USER=neo4j"
  echo "NEO4J_PASSWORD=$PW"
  echo "NEO4J_DATABASE=neo4j"
} >> "$ENV.tmp"
mv "$ENV.tmp" "$ENV"; chmod 600 "$ENV"

cat <<EOF

  Neo4j is up.
    bolt    bolt://127.0.0.1:$BOLT
    browser http://127.0.0.1:$HTTP   (ssh -L $HTTP:127.0.0.1:$HTTP $(hostname))
    store   $DATA_DIR/data
    logs    $DATA_DIR/logs/neo4j.log
    status  '$NEO4J_HOME/bin/neo4j status'

  Credentials written to .env (mode 600). Password also at $DATA_DIR/password.
EOF
